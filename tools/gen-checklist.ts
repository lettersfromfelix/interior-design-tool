/**
 * npm run checklist — write docs/measurement-checklist.md from the "checks" in data/apartment.json.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { ApartmentFile } from "../src/core/schema/apartment";

const root = resolve(import.meta.dirname, "..");
const ap = ApartmentFile.parse(JSON.parse(readFileSync(resolve(root, "data/apartment.json"), "utf8")));
const checks = ap.checks ?? [];

const fmt = (v: number, unit: string) => (unit === "deg" ? `${v.toFixed(0)}°` : `${v.toFixed(1)} cm`);
const row = (c: (typeof checks)[number]) =>
  `| **${c.id}** | ${c.title} | ${c.how} | ${c.planValue ? fmt(c.planValue, c.unit) : "–"} | ${c.measured !== undefined ? fmt(c.measured, c.unit) : ""} |`;

const lines = [
  "# Measurement checklist",
  "",
  "<!-- Generated by `npm run checklist` from data/apartment.json (checks). Do not edit the tables by hand. -->",
  "",
  "These values were derived from the floor plan. The plan has no heights, so all heights are estimates.",
  "Please check them with a tape measure:",
  "",
  "1. Take the **must** items first. The **nice** items are optional.",
  '2. Open the tool and select an item in the **Verify** panel. The 2D and 3D views then show a magenta dimension line for exactly what to measure.',
  "3. Write your result into the *Measured* column, or just send the numbers to GHCP. GHCP will set `measured` on the check, correct the geometry in `data/apartment.json`, and mark it as `source: \"measured\"` / `confidence: \"high\"`.",
  "",
  "Measure clear dimensions, finished wall surface to finished wall surface, at about 1 m above the floor.",
  "",
  "## Must",
  "",
  "| # | What | How | Model now | Measured |",
  "|---|---|---|---|---|",
  ...checks.filter((c) => c.priority === "must").map(row),
  "",
  "## Nice to have",
  "",
  "| # | What | How | Model now | Measured |",
  "|---|---|---|---|---|",
  ...checks.filter((c) => c.priority === "nice").map(row),
  "",
];
writeFileSync(resolve(root, "docs/measurement-checklist.md"), lines.join("\n"));
console.log(`wrote docs/measurement-checklist.md (${checks.length} checks)`);
